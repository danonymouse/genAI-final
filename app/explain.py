"""Stage 4: turn a flagged span plus its retrieved entries into an explanation.

Three sources, tried in this order (EXPLAIN_MODE=auto):
  live    - Claude, grounded in the retrieved lexicon entries. One call per line.
  cache   - explanations pre-generated by scripts/generate_cache.py, shipped in the image.
  lexicon - no LLM: the best entry's fields, rendered as-is. Keeps the container useful
            with no API key and no cache hit.

Claude can also reject the retrieved entries ("fits_context": false), e.g. 미친 used
literally. That span is then marked uncertain instead of explained: the second gate
against hallucination, after the similarity threshold.
"""
from __future__ import annotations

import hashlib
import json
import logging
from dataclasses import dataclass, field
from pathlib import Path

from .schemas import Explanation, FlaggedSpan, Lang, LexiconEntry

log = logging.getLogger(__name__)

PROMPT_VERSION = "v1"
LANG_NAME = {"ko": "Korean", "zh": "Mandarin Chinese"}

SYSTEM_PROMPT = """You explain real {lang_name} speech to English-speaking learners.

You receive one transcript line, the neighbouring lines for context, and a list of flagged spans. Each span comes with dictionary entries retrieved for it.

For every span:
1. Decide whether any retrieved entry matches how the span is used *in this line*. If none does (for example the speaker uses the words literally), set fits_context to false and leave the other fields empty. Do not explain a span from your own knowledge when the entries do not fit.
2. Otherwise explain it, grounded in the matching entry, adapted to this context:
   - literal: the word-for-word meaning a translation tool would give
   - function: what the speaker is actually doing with it here
   - why_mt_misses: why a literal translation misleads, in one sentence
   - register: who says this to whom, and how casual or crude it is
   - textbook_equivalent: what a textbook would write instead, in {lang_name}

Be brief: one short sentence per field. Plain English, no jargon."""

TOOL = {
    "name": "record_explanations",
    "description": "Record one explanation per flagged span.",
    "input_schema": {
        "type": "object",
        "properties": {
            "items": {
                "type": "array",
                "items": {
                    "type": "object",
                    "properties": {
                        "span_index": {"type": "integer"},
                        "fits_context": {"type": "boolean"},
                        "literal": {"type": "string"},
                        "function": {"type": "string"},
                        "why_mt_misses": {"type": "string"},
                        "register": {"type": "string"},
                        "textbook_equivalent": {"type": "string"},
                    },
                    "required": ["span_index", "fits_context"],
                },
            }
        },
        "required": ["items"],
    },
}


@dataclass
class SpanJob:
    """One span that passed the retrieval threshold and needs an explanation."""
    span: FlaggedSpan
    entries: list[LexiconEntry]


@dataclass
class SpanResult:
    explanation: Explanation | None
    source: str | None  # live | cache | lexicon
    rejected: bool = False  # Claude said no entry fits this context


@dataclass
class Explainer:
    lang: Lang
    cache_path: Path
    api_key: str | None = None
    model: str = "claude-sonnet-5-5"
    mode: str = "auto"
    cache: dict = field(default_factory=dict)
    warnings: list[str] = field(default_factory=list)
    _client: object = None

    def __post_init__(self):
        if self.cache_path.exists():
            self.cache = json.loads(self.cache_path.read_text(encoding="utf-8"))

    @property
    def live_enabled(self) -> bool:
        return bool(self.api_key) and self.mode in ("auto", "live")

    @property
    def cache_enabled(self) -> bool:
        return self.mode in ("auto", "cache")

    # ------------------------------------------------------------------ #
    @staticmethod
    def cache_key(lang: str, line: str, job: SpanJob) -> str:
        ids = ",".join(e.id for e in job.entries)
        raw = "\x1f".join([PROMPT_VERSION, lang, line, str(job.span.start), str(job.span.end), ids])
        return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:24]

    def save_cache(self) -> None:
        self.cache_path.parent.mkdir(parents=True, exist_ok=True)
        self.cache_path.write_text(
            json.dumps(self.cache, ensure_ascii=False, indent=1, sort_keys=True), encoding="utf-8"
        )

    # ------------------------------------------------------------------ #
    def explain_line(self, line: str, context: list[str], jobs: list[SpanJob]) -> list[SpanResult]:
        if not jobs:
            return []
        results: list[SpanResult | None] = [None] * len(jobs)

        if self.live_enabled:
            try:
                live = self._call_claude(line, context, jobs)
                for i, r in enumerate(live):
                    results[i] = r
                    if r is not None:
                        self.cache[self.cache_key(self.lang, line, jobs[i])] = _to_cache(r)
            except Exception as e:  # network, auth, rate limit: degrade, don't fail the request
                msg = f"live explanation failed ({type(e).__name__}); fell back to cache/lexicon"
                if msg not in self.warnings:
                    self.warnings.append(msg)
                log.warning("claude call failed: %s", e)

        for i, job in enumerate(jobs):
            if results[i] is not None:
                continue
            if self.cache_enabled:
                hit = self.cache.get(self.cache_key(self.lang, line, job))
                if hit is not None:
                    results[i] = _from_cache(hit)
                    continue
            results[i] = SpanResult(_from_entry(job.entries[0]), "lexicon")
        return results  # type: ignore[return-value]

    # ------------------------------------------------------------------ #
    def _client_lazy(self):
        if self._client is None:
            import anthropic

            self._client = anthropic.Anthropic(api_key=self.api_key, max_retries=2, timeout=60)
        return self._client

    def _call_claude(self, line: str, context: list[str], jobs: list[SpanJob]) -> list[SpanResult | None]:
        payload = {
            "line": line,
            "context": context,
            "spans": [
                {
                    "span_index": i,
                    "surface": j.span.surface,
                    "start": j.span.start,
                    "end": j.span.end,
                    "entries": [
                        e.model_dump(include={"headword", "type", "literal", "meaning", "register",
                                              "textbook_equivalent", "mt_pitfall", "example"})
                        for e in j.entries
                    ],
                }
                for i, j in enumerate(jobs)
            ],
        }
        resp = self._client_lazy().messages.create(
            model=self.model,
            max_tokens=2000,
            temperature=0,
            system=SYSTEM_PROMPT.format(lang_name=LANG_NAME[self.lang]),
            tools=[TOOL],
            tool_choice={"type": "tool", "name": TOOL["name"]},
            messages=[{"role": "user", "content": json.dumps(payload, ensure_ascii=False)}],
        )
        block = next(b for b in resp.content if b.type == "tool_use")
        out: list[SpanResult | None] = [None] * len(jobs)
        for item in block.input.get("items", []):
            i = item.get("span_index")
            if not isinstance(i, int) or not 0 <= i < len(jobs):
                continue
            if not item.get("fits_context", False):
                out[i] = SpanResult(None, "live", rejected=True)
                continue
            try:
                out[i] = SpanResult(
                    Explanation(**{k: item.get(k, "") for k in Explanation.model_fields}), "live"
                )
            except Exception:
                out[i] = None
        return out


def _from_entry(e: LexiconEntry) -> Explanation:
    return Explanation(
        literal=e.literal,
        function=e.meaning,
        why_mt_misses=e.mt_pitfall,
        register=e.register,
        textbook_equivalent=e.textbook_equivalent,
    )


def _to_cache(r: SpanResult) -> dict:
    return {"rejected": r.rejected, "explanation": r.explanation.model_dump() if r.explanation else None}


def _from_cache(d: dict) -> SpanResult:
    exp = Explanation(**d["explanation"]) if d.get("explanation") else None
    return SpanResult(exp, "cache", rejected=bool(d.get("rejected")))
